package main

import (
	"os"
	"path/filepath"
	"testing"
)

func TestAnalyzeRootCountsProductionOnly(t *testing.T) {
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "main.go"), []byte(`package sample

type Small struct { A int; B string }

type Big struct {
	One int
	Two int
	Three int
}

func plain() {}

func (s Small) method() {}
`), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "main_test.go"), []byte("package sample\nfunc TestIgnored() {}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "generated.go"), []byte("// Code generated by test. DO NOT EDIT.\npackage sample\nfunc generated() {}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	result, err := analyzeRoot(root, 2)
	if err != nil {
		t.Fatal(err)
	}
	if result.Files != 1 || result.Functions != 1 || result.Methods != 1 || result.Structs != 2 || result.Fields != 5 {
		t.Fatalf("report = %+v", result)
	}
	if len(result.TopFunctions) != 2 || result.TopFunctions[0].Name != "Small.method" || result.TopFunctions[1].Name != "plain" {
		t.Fatalf("functions = %+v", result.TopFunctions)
	}
	if len(result.TopStructs) != 2 || result.TopStructs[0].Name != "Big" || result.TopStructs[0].Count != 3 {
		t.Fatalf("structs = %+v", result.TopStructs)
	}
}
